#!/usr/bin/env bash
# Combines backend/*.gs into one file that can be pasted into Apps Script's Code.gs.
set -euo pipefail
cd "$(dirname "$0")/.."
out=backend/ALL-IN-ONE.gs
{
  echo "// ACS Project Tracker backend: ALL FILES IN ONE."
  echo "// Paste this whole file into Code.gs in Apps Script (replace everything there)."
  echo "// Generated by tools/bundle-backend.sh; edit the separate backend/*.gs files instead."
  for f in Code Sheets Auth Actions Setup; do
    echo; echo "// ===================== $f.gs ====================="; echo
    cat "backend/$f.gs"
  done
} > "$out"
echo "wrote $out"
